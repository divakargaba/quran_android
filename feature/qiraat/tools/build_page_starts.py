"""Writes RiwayahPages.kt: the first ayah (Hafs numbering) on each page of every riwayah mushaf,
and the part of the page its text occupies.

usage: build_page_starts.py <dir with <riwayah>.qrx> <dir with stream pickles> <out .kt>
"""
import sys, os, gzip, struct, pickle
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
import align
from madani import AYAHS

NAMES = dict(zip([10,16,20,6,17,7,9,18,4,15,12,11,0,8,5,3,14,13,2,1],
  'hafs,qalun,warsh,bazzi,qunbul,duri_abuamr,susi,hisham,ibndhakwan,shubah,khalaf,khallad,'
  'abulharith,duri_kisai,ibnwardan,ibnjammaz,ruways,rawh,ishaq,idris'.split(',')))
qrx_dir, stream_dir, out = sys.argv[1:4]

def ayah_pages(path):
    d = gzip.open(path).read(); o = 6; result = []
    while o < len(d):
        page, number, n = struct.unpack('>HHB', d[o:o + 5]); o += 5
        pages = [struct.unpack('>H', d[o + 10 * i:o + 10 * i + 2])[0] for i in range(n)]
        o += 10 * n
        result.append(sorted(set(pages)) or [page])
    return result

keys = [(s, a) for s, c in enumerate(AYAHS, 1) for a in range(1, c + 1)]
lines = ['package com.quran.mobile.feature.qiraat.pages', '',
         '// Generated by tools/build_page_starts.py; do not edit.', '',
         'internal object RiwayahPages {', '',
         '  /** for each riwayah, "sura:ayah" of the first ayah on each of the 604 pages */',
         '  val pageStarts: Map<String, String> = mapOf(']
bounds = {}
for index, name in NAMES.items():
    pages = ayah_pages(f'{qrx_dir}/{name}.qrx')
    starts = []
    for p in range(1, 605):
        first = next((k for k, ps in zip(keys, pages) if ps[0] == p), None)
        if first is None:  # the page is all one ayah that began on an earlier page
            first = next(k for k, ps in zip(keys, pages) if p in ps)
        starts.append(first)
    assert starts == sorted(starts), name
    lines.append(f'    "{name}" to "' + ','.join(f'{s}:{a}' for s, a in starts) + '",')
    st = align.body_filter(pickle.load(open(f'{stream_dir}/r{index}.pkl', 'rb')))
    t = np.array([x[2:6] for x in st if x[0] > 2])
    bounds[name] = (max(0, np.percentile(t[:, 0], 0.2) - 0.015), max(0, np.percentile(t[:, 1], 0.2) - 0.012),
                    min(1, np.percentile(t[:, 2], 99.8) + 0.015), min(1, np.percentile(t[:, 3], 99.8) + 0.012))
lines[-1] = lines[-1].rstrip(',')
lines += ['  )', '',
          '  /** for each riwayah, the part of its pages (left, top, right, bottom) its text is in */',
          '  val textBounds: Map<String, FloatArray> = mapOf(']
for name, b in bounds.items():
    lines.append(f'    "{name}" to floatArrayOf({b[0]:.3f}f, {b[1]:.3f}f, {b[2]:.3f}f, {b[3]:.3f}f),')
lines[-1] = lines[-1].rstrip(',')
lines += ['  )', '}', '']
open(out, 'w').write('\n'.join(lines))
